#Comparision operators exercise
a=3
b=6
result= a==b #Equal to comparision operator
print("result of",a, "==",b,"is : ", result)
result= a!=b #Not equal to comparision operator
print("result of",a, "!=",b,"is : ", result)
result= a >b #Greater than comparision operator
print("result of",a, ">",b,"is : ", result)
result= a<b #Less than comparision operator
print("result of",a, "<",b,"is : ", result)
result= a>=b #Greater than or equal to
print("result of",a, ">=",b,"is : ", result)
result= a<=b #Less than or equal to
print("result of",a, "<=",b,"is : ", result)