#Write a python program to print numbers from 1 to N using for loop.
n=int(input("Enter the value of n: "))
for i in range(1, n+1):
    print(i)
#Write a python program to print numbers from 1 to N using while loop.
n = int(input("Enter the value of n: "))
i = 1
while i <= n:
    print(i)
    i = i + 1